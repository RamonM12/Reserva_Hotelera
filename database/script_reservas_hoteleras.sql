-- Sistema de Gestión de Reservas Hoteleras
-- Base de datos Oracle. Usuario: HOTEL
-- Sin llaves foráneas entre tablas (cada microservicio es dueño de su tabla)

CREATE TABLE HUESPEDES (
    ID_HUESPED       NUMBER GENERATED BY DEFAULT AS IDENTITY,
    NOMBRE           VARCHAR2(50)  NOT NULL,
    APELLIDO         VARCHAR2(50)  NOT NULL,
    EMAIL            VARCHAR2(254) NOT NULL,
    TELEFONO         VARCHAR2(10)  NOT NULL,
    TIPO_DOCUMENTO   VARCHAR2(9)   NOT NULL,
    NUMERO_DOCUMENTO VARCHAR2(20)  NOT NULL,
    NACIONALIDAD     VARCHAR2(50)  NOT NULL,
    ESTADO_REGISTRO  VARCHAR2(9)   DEFAULT 'ACTIVO' NOT NULL,
    CONSTRAINT PK_HUESPEDES PRIMARY KEY (ID_HUESPED)
);

CREATE TABLE HABITACIONES (
    ID_HABITACION   NUMBER GENERATED BY DEFAULT AS IDENTITY,
    NUMERO          NUMBER        NOT NULL,
    TIPO            VARCHAR2(8)   NOT NULL,
    PRECIO          NUMBER        NOT NULL,
    CAPACIDAD       NUMBER        NOT NULL,
    ESTADO          VARCHAR2(13)  DEFAULT 'DISPONIBLE' NOT NULL,
    ESTADO_REGISTRO VARCHAR2(9)   DEFAULT 'ACTIVO' NOT NULL,
    CONSTRAINT PK_HABITACIONES PRIMARY KEY (ID_HABITACION)
);

CREATE TABLE RESERVAS (
    ID_RESERVA      NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ID_HUESPED      NUMBER        NOT NULL,
    ID_HABITACION   NUMBER        NOT NULL,
    FECHA_ENTRADA   DATE          NOT NULL,
    FECHA_SALIDA    DATE          NOT NULL,
    NUMERO_PERSONAS NUMBER        NOT NULL,
    PRECIO_NOCHE    NUMBER        NOT NULL,
    PRECIO_TOTAL    NUMBER        NOT NULL,
    ESTADO          VARCHAR2(10)  DEFAULT 'CONFIRMADA' NOT NULL,
    ESTADO_REGISTRO VARCHAR2(9)   DEFAULT 'ACTIVO' NOT NULL,
    CONSTRAINT PK_RESERVAS PRIMARY KEY (ID_RESERVA)
);
